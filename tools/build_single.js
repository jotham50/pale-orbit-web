// Bundle index.html and its scripts into one self-contained file.
//   node tools/build_single.js   ->  pale-orbit.html
const fs = require("fs");
const path = require("path");
const rootDir = path.resolve(__dirname, "..");
let html = fs.readFileSync(path.join(rootDir, "index.html"), "utf8");
html = html.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
  const code = fs.readFileSync(path.join(rootDir, src), "utf8").replace(/<\/script/gi, "<\\/script");
  return `<script>/* ${src} */\n${code}\n</script>`;
});
html = html.replace("<title>Pale Orbit</title>",
                    "<title>Pale Orbit</title>\n<!-- single-file build: generated by tools/build_single.js -->");
fs.writeFileSync(path.join(rootDir, "pale-orbit.html"), html);
console.log(`wrote pale-orbit.html (${(html.length / 1024).toFixed(0)} KB)`);
